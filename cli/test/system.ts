import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { setImmediate as nextTurn } from "node:timers/promises";
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),"surface-system-test-"));
process.env.SURFACE_CONFIG_DIR=tmp;
delete process.env.SURFACE_SUPABASE_URL; delete process.env.SURFACE_PUBLISHABLE_KEY;
const {signedInAccount,installedVersion,systemInfo}=await import("../src/system.ts");
const realFetch = globalThis.fetch;
let probes = 0;
let failProbe = false;
let finishProbe: (() => void) | undefined;
globalThis.fetch = async (input, init) => {
  probes++;
  assert.match(String(input), /\/auth\/v1\/health$/);
  assert.equal(init?.redirect, "manual", "configured endpoints cannot redirect probes to third parties");
  assert.ok(init?.signal, "endpoint checks have a bounded deadline");
  const completion = Promise.withResolvers<void>();
  finishProbe = completion.resolve;
  await completion.promise;
  if (failProbe) throw new Error("fetch failed");
  return new Response(null, { status: 401 });
};
async function completeProbe() {
  finishProbe?.();
  await nextTurn();
}
try {
  assert.equal(signedInAccount(),null);
  assert.deepEqual(systemInfo().cloudConnectivity, { state: "unconfigured", target: null, checkedAt: null, checking: false });
  assert.equal(probes, 0, "local-only status never contacts a third party");
  fs.writeFileSync(path.join(tmp,"cloud.json"),JSON.stringify({url:"https://team.supabase.co",publishableKey:"public-key"}));
  fs.writeFileSync(path.join(tmp,"session.json"),JSON.stringify({"sb-team-auth-token":JSON.stringify({access_token:"private-access",refresh_token:"private-refresh",user:{id:"signup-user-id",email:"user@example.com",user_metadata:{full_name:"Team Member"}}}),"sb-other-auth-token":JSON.stringify({user:{id:"wrong-project",email:"other@example.com"}})}));
  assert.deepEqual(signedInAccount(),{id:"signup-user-id",email:"user@example.com",name:"Team Member"});
  const info=systemInfo(); assert.equal(info.account?.id,"signup-user-id");
  assert.equal(JSON.stringify(info).includes("private-"),false);
  assert.deepEqual(info.cloudConnectivity, { state: "unknown", target: "https://team.supabase.co/auth/v1/health", checkedAt: null, checking: true });
  assert.equal("job" in info.update, false, "release currency is read-only, without updater job state");
  systemInfo();
  assert.equal(probes, 1, "concurrent status reads share one observation");
  await completeProbe();
  const reachable = systemInfo().cloudConnectivity;
  assert.equal(reachable.state, "online", "HTTP auth failures prove reachability, not database authorization");
  assert.ok(reachable.checkedAt);
  assert.equal(reachable.checking, false);
  assert.equal(probes, 1, "fresh observations are cached across polling requests");
  failProbe = true;
  fs.writeFileSync(path.join(tmp,"cloud.json"),JSON.stringify({url:"http://unreachable.invalid",publishableKey:"public-key"}));
  const checking = systemInfo().cloudConnectivity;
  assert.equal(checking.state, "unknown", "a changed target cannot inherit another target's result");
  assert.equal(checking.checkedAt, null);
  await completeProbe();
  const unreachable = systemInfo().cloudConnectivity;
  assert.equal(unreachable.state, "unreachable");
  assert.equal(unreachable.target, "http://unreachable.invalid/auth/v1/health");
  assert.ok(unreachable.checkedAt);
  assert.equal("internet" in systemInfo(), false, "one endpoint failure is not evidence about the internet");
  fs.writeFileSync(path.join(tmp,"cloud.json"),JSON.stringify({url:"not-a-url",publishableKey:"public-key"}));
  assert.deepEqual(systemInfo().cloudConnectivity, { state: "unknown", target: null, checkedAt: null, checking: false });
  fs.writeFileSync(path.join(tmp,"cloud.json"),JSON.stringify({url:"https://team.supabase.co",publishableKey:"public-key"}));
  const installed=installedVersion();
  const running={number:"0.0.9",commit:"0".repeat(40)};
  fs.writeFileSync(path.join(tmp,"update.json"),JSON.stringify({current:installed.commit,available:"b".repeat(40),availableVersion:"0.2.0",updateAvailable:true,checkedAt:new Date().toISOString()}));
  const checked=systemInfo(running);
  assert.deepEqual(checked.version,installed,"installed version follows the checkout checked by the updater");
  assert.deepEqual(checked.runningVersion,running,"the server's startup revision stays independently visible");
  assert.equal(checked.update.available,true,"a completed check remains visible after HEAD changes without a restart");
  assert.equal(checked.update.availableCommit,"b".repeat(40));
  assert.ok(checked.update.checkedAt);
  fs.writeFileSync(path.join(tmp,"session.json"),JSON.stringify({"sb-team-auth-token":"broken"})); assert.equal(signedInAccount(),null);
  fs.writeFileSync(path.join(tmp,"session.json"),"{}");assert.equal(signedInAccount(),null);
  console.log("System info: actual signup identity, correct cloud, no exposed credentials, local/signed-out display and installed revision passed.");
} finally {globalThis.fetch=realFetch; finishProbe?.(); fs.rmSync(tmp,{recursive:true,force:true});}
